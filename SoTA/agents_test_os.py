class DataProcessing:
    def __init__(self, data: List[str]):
        self.data = data

    def process_data(self, code: str):
        try:
            exec(code, {'data': self.data, 'sr': sr})
            return locals().get('processed_data', [])
        except Exception as e:
            print(f"Error executing code: {e}")
